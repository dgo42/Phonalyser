package org.edgo.audio.measure.gui.fft;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * One pilot line's reading: the phase gained since the collection's FIRST
 * frame, on the nearest branch of one turn, and nothing else.  Every raw phase
 * the reader is given is generated by the test from the turns the line has
 * made, folded onto one turn, as that fold is all a frame ever shows.  The
 * zero is taken once and never moves, so every reading is absolute and no
 * frame's error can reach the next.
 */
class PilotReaderTest {

    /** The bin the line sits on - carried through the reading, never read
     *  from. */
    private static final int    PILOT_BIN    = 106801;
    private static final int    FFT_SIZE     = 1 << 21;
    /** Samples between two accepted frames. */
    private static final int    HOP_SAMPLES  = 2048;
    /** The turns the line makes over one hop, bin times hop over the transform
     *  size - a hundred of them whole, which no single reading can show. */
    private static final double TURNS_PER_HOP = (double) PILOT_BIN * HOP_SAMPLES / FFT_SIZE;
    private static final double TURN_RAD      = 2.0 * Math.PI;
    /** What a reading may miss its generated value by, radians. */
    private static final double TOL           = 1.0e-9;
    /** The fixed offset a reading at the bin carries, radians: the generator's
     *  starting phase, the converter's delay and the window's phase at the bin
     *  together - the same in every frame, so it cancels between two. */
    private static final double OFFSET_RAD    = 2.4;
    /** Frames read after the first one. */
    private static final int    FRAMES        = 5;

    /** All a frame shows of a line that has made {@code turns} turns since the
     *  reading began: the fixed offset plus the fraction of a turn left over,
     *  folded onto the nearest turn. */
    private double rawPhase(double turns) {
        return Math.IEEEremainder(OFFSET_RAD + TURN_RAD * (turns - Math.rint(turns)), TURN_RAD);
    }

    /** Before the first frame is taken there is nothing to measure against: a
     *  reading gives zero and holds nothing; taking the frame sets the zero,
     *  which the same phase read again shows as no change. */
    @Test
    void nothingIsMeasuredBeforeTheFirstFrame() {
        PilotReader reader = new PilotReader(PILOT_BIN);
        assertEquals(PILOT_BIN, reader.getBin(), "the line's bin");
        assertFalse(reader.isFirstTaken(), "no zero yet");

        double first = rawPhase(0.0);
        assertEquals(0.0, reader.changeSince(first), TOL, "no zero, no change");
        assertFalse(reader.isFirstTaken(), "a reading alone sets nothing");
        reader.takeFirst(first);
        assertTrue(reader.isFirstTaken(), "the first frame is the zero every reading is taken from");
        assertEquals(0.0, reader.changeSince(first), TOL, "the same phase again is no change");
    }

    /** Two frames straddling the fold of the raw phase come back as the short
     *  way round, not as the near-whole turn the two numbers differ by. */
    @Test
    void aChangeAcrossAWrapComesBackOnTheNearestBranch() {
        double before = 3.0;
        double after  = -3.0;

        PilotReader forward = new PilotReader(PILOT_BIN);
        forward.takeFirst(before);
        assertEquals(after - before + TURN_RAD, forward.changeSince(after), TOL,
                "forward across plus pi");

        PilotReader backward = new PilotReader(PILOT_BIN);
        backward.takeFirst(after);
        assertEquals(before - after - TURN_RAD, backward.changeSince(before), TOL,
                "back across minus pi");
    }

    /** Every frame is measured against the FIRST one: a line advancing
     *  {@link #TURNS_PER_HOP} turns a frame gives that many turns' worth of
     *  fraction at frame one, twice at frame two and so on, and a frame that
     *  is read and not used changes nothing for the frames after it. */
    @Test
    void everyReadingIsMeasuredAgainstTheFirstFrame() {
        PilotReader reader = new PilotReader(PILOT_BIN);
        reader.takeFirst(rawPhase(0.0));
        for (int frame = 1; frame <= FRAMES; frame++) {
            double sinceFirst = frame * TURNS_PER_HOP;
            double expected   = TURN_RAD * (sinceFirst - Math.rint(sinceFirst));
            assertEquals(expected, reader.changeSince(rawPhase(sinceFirst)), TOL,
                    "the change since the first frame, read at frame " + frame);
        }
        // reading a frame is all the reader does: the zero does not move, so
        // the frame after any reading is still measured from the first one
        double later   = (FRAMES + 3) * TURNS_PER_HOP;
        double expected = TURN_RAD * (later - Math.rint(later));
        assertEquals(expected, reader.changeSince(rawPhase(later)), TOL,
                "a later frame, still measured from the first");
    }

    /** A reset forgets the zero - the collection is over, and the next frame
     *  becomes a first frame of its own. */
    @Test
    void aResetForgetsTheZero() {
        PilotReader reader = new PilotReader(PILOT_BIN);
        reader.takeFirst(rawPhase(0.0));
        assertTrue(reader.isFirstTaken(), "a zero is held");

        reader.reset();
        assertFalse(reader.isFirstTaken(), "the zero is gone");
        double fresh = rawPhase(2.0 * TURNS_PER_HOP);
        assertEquals(0.0, reader.changeSince(fresh), TOL, "nothing to measure against");
        reader.takeFirst(fresh);
        assertEquals(0.0, reader.changeSince(fresh), TOL, "and the new zero is held");
    }
}
