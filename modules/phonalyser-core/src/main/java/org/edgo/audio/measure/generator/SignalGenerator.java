    /**
     * Pink noise via the Voss-McCartney summed-octave algorithm.
     *
     * @param linear true  -> uniformly distributed white source (flat amplitude PDF)
     *               false -> Gaussian white source
     */
    private double pinkNoise(boolean linear) {
        pinkCounter++;
        int trailing = Long.numberOfTrailingZeros(pinkCounter);
        if (trailing < PINK_OCTAVES) {
            double newVal = linear ? (rng.nextDouble() * 2.0 - 1.0) : rng.nextGaussian();
            pinkRunningSum += newVal - pinkRows[trailing];
            pinkRows[trailing] = newVal;
        }
        double white = linear ? (rng.nextDouble() * 2.0 - 1.0) : rng.nextGaussian();
        return (pinkRunningSum + white) / (PINK_OCTAVES + 1.0);
    }

    // -------------------------------------------------------------------------
    // Harmonic compensation
    // -------------------------------------------------------------------------

    /**
     * Loads a predistortion-correction file onto this running generator and
     * switches to the matching compensated form - the wizard's "Apply" and the
     * relaunch path both route through here.  The file format is
     * self-describing: a single-tone (harmonic) file's column header begins
     * {@code harmonic;...}; a dual-tone (intermod) file's begins {@code a;b;...}.
     *
     * @param frequency  fundamental (single-tone) frequency in Hz; ignored for
     *                   dual-tone files (the {@code a·f₁+b·f₂} products follow
     *                   the generator's live tone frequencies)
     */
    public void readDpd(String path, double frequency, int sampleRate) throws IOException {
        new Predistortion(path, frequency, sampleRate).applyTo(this);
    }

    /**
     * DDS sine with H2..Hn harmonic compensation.
     *
     * Each harmonic's phase is derived by integer-multiplying the master 32-bit
     * phase accumulator by the harmonic number.  This locks the compensation
     * frequency exactly to h·f_DDS - no drift, no beating against the real
     * distortion harmonics, regardless of how many samples have been generated.
     */
    private double ddsSineCompensated() {
        double s = ddsSine();
        Compensation c = comp;                 // single volatile read - atomic hot-swap
        if (c != null) {
            for (int i = 0; i < c.amp.length; i++) {
                long hPhase = phaseAcc * c.hNum[i] + c.phaseOff64[i];   // wraps mod 2^64
                s -= c.amp[i] * ddsCos(hPhase);
            }
        }
        return s;
    }

    /**
     * DDS two-tone with intermodulation + harmonic compensation.
     *
     * <p>Emits the uncorrected dual-tone sum, then subtracts an anti-phase
     * correction tone for every accumulated distortion product.  Each product
     * sits at {@code a·f₁ + b·f₂}, so its phase is the same integer combination
     * of the two accumulators - {@code a·phaseAcc + b·phaseAcc2} - formed in
     * {@code long} arithmetic where overflow IS the 2⁶⁴ phase wrap.  This locks
     * every correction exactly to its product frequency with no drift or
     * beating, no matter how many samples have been generated.
     *
     * <p>Each {@code ampRatio} is a ratio to the <b>F1 TONE</b>, so it is
     * scaled by that tone's own weight - the {@code w₁} that multiplies
     * {@code ddsSine()} on the very first line - and not by full scale.  The
     * single-tone kernel needs no such factor only because there the
     * fundamental IS the whole raw waveform, at weight 1.  Scaled here rather
     * than folded into the published table because the weights are
     * live-swappable: a split change must move the corrections with the tone,
     * not leave a table that was baked against the old split.
     */
    private double ddsDualToneCompensated() {
        double w1 = dualW1;                    // single volatile read - also the ratio reference
        double s = ddsSine() * w1 + ddsSine2() * dualW2;
        DualToneComp c = dtComp;               // single volatile read - atomic hot-swap
        if (c != null) {
            for (int i = 0; i < c.amp.length; i++) {
                long pPhase = phaseAcc * c.a[i] + phaseAcc2 * c.b[i] + c.phaseOff64[i];
                s -= c.amp[i] * w1 * ddsCos(pPhase);
            }
        }
        return s;
    }

    /** Table + Taylor cosine of an arbitrary 64-bit DDS phase accumulator -
     *  the shared kernel's cosine identity, same error budget.  Used by the
     *  harmonic-compensation kernel so no {@code Math.cos} runs on the
     *  per-sample path. */
    private double ddsCos(long acc) {
        return SineKernel.cosAtPhaseAcc(acc);
    }

