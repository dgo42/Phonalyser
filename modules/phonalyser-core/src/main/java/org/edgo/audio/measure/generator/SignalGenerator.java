    /**
     * Live-swaps the waveform.  Phase accumulator is preserved so the
     * transition between phase-continuous forms (sine/saw/triangle) is
     * smooth.  Switching <em>to</em> {@link GenSignalForm#SINE_COMP}
     * without previously loading harmonics simply produces an uncorrected
     * sine - the per-harmonic correction arrays remain {@code null}.
     * Sweep forms expect their own constructor and shouldn't be reached
     * via this setter.
     */
    public void setForm(GenSignalForm newForm) {
        if (newForm == null || newForm == form) return;
        // Re-scale both lanes' levels so the new form keeps the same V RMS
        // output - sine and triangle / saw / noise have different peak / RMS
        // ratios.  The cached Vrms is "what the user dialled" and gets
        // re-divided against the new form's rawRms.
        this.form = newForm;
        recomputeLevels();
    }

    /** Stores both lanes' commanded amplitudes and full scales and derives the
     *  two digital levels from them - the one place the four meet, so a lane's
     *  level can never be computed from the other lane's full scale. */
    private void applyLanes(double vrmsLeft, double vrmsRight, double fsAmplLeft,
            double fsAmplRight) {
        this.currentVrmsLeft       = vrmsLeft;
        this.currentVrmsRight      = vrmsRight;
        this.dacFsVoltageAmplLeft  = fsAmplLeft;
        this.dacFsVoltageAmplRight = fsAmplRight;
        recomputeLevels();
    }

    /** Re-derives both lanes' levels from the cached amplitudes and full scales
     *  against the current form's peak / RMS ratio, and each pilot's two lane
     *  levels from its own V RMS - a pilot is a sine whatever the form is, so
     *  it converts at a sine's peak / RMS ratio and never at the form's. */
    private void recomputeLevels() {
        double raw = rawRms(form);
        this.amplitudeLeft   = currentVrmsLeft  / (dacFsVoltageAmplLeft  * raw);
        this.amplitudeRight  = currentVrmsRight / (dacFsVoltageAmplRight * raw);
        this.pilotAmplLeft   = pilotVrms  * Constants.SQRT2 / dacFsVoltageAmplLeft;
        this.pilotAmplRight  = pilotVrms  * Constants.SQRT2 / dacFsVoltageAmplRight;
        this.pilotAmplLeft2  = pilotVrms2 * Constants.SQRT2 / dacFsVoltageAmplLeft;
        this.pilotAmplRight2 = pilotVrms2 * Constants.SQRT2 / dacFsVoltageAmplRight;
        this.pilotFadeCoef   = sampleRate > 0
                ? 1.0 - Math.exp(-1.0 / (PILOT_FADE_TAU_S * sampleRate)) : 1.0;
    }

    /** One sample of a pilot level's fade toward its target, snapped to
     *  silence once a line fading out has fallen below any resolution. */
    private double fadeToward(double current, double target, double coef) {
        double next = current + (target - current) * coef;
        return (target == 0.0 && Math.abs(next) < PILOT_SILENT) ? 0.0 : next;
    }

    /** Sets both lanes' digital levels directly - for a source whose samples
     *  are not a waveform at a voltage but a file at a gain per lane. */
    protected void setLevels(double left, double right) {
        this.amplitudeLeft  = left;
        this.amplitudeRight = right;
    }

    /**
     * Live-updates the output frequency (Hz).  Phase accumulator is
     * preserved so the change is phase-continuous (no audible click).
     * Sweep forms ignore this - their instantaneous frequency is driven
     * by their own state machine.
     */
    public void setFrequency(double frequencyHz) {
        this.frequencyHz = frequencyHz;
        this.phaseInc    = toPhaseInc(frequencyHz);
    }

    /**
     * Hot-swaps the harmonic compensation on the RUNNING generator and
     * switches it to {@link GenSignalForm#SINE_COMP} - the
     * predistortion wizard applies each round's corrections this way, with
     * no audio restart.  The phasors {@code (ampRatio, harmonic number,
     * initial phase)} are published as one immutable {@link Compensation}
     * before the form flips, so the audio thread never sees a
     * partially-updated set.  Empty arrays leave an uncorrected sine.
     */
    public void applyCompensation(double[] ampRatios, int[] hNums, double[] phiInits) {
        this.comp = new Compensation(ampRatios, hNums, phiInits);
        this.form = GenSignalForm.SINE_COMP;
        logCompensation(ampRatios, hNums, phiInits);
    }

    /** The harmonic set as it reaches the DDS - ratio to the fundamental in
     *  percent and initial phase in degrees, the numbers a {@code .dpd} row
     *  carries - so a round's hot-swap and a file load read alike in the
     *  log and can be compared. */
    private void logCompensation(double[] ampRatios, int[] hNums, double[] phiInits) {
        if (!log.isInfoEnabled()) return;
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < hNums.length; i++) {
            double deg = Math.toDegrees(phiInits[i]);
            deg -= 360.0 * Math.round(deg / 360.0);
            sb.append(String.format(Locale.US, " H%d %.4e %% %+.2f deg;",
                    hNums[i], ampRatios[i] * 100.0, deg));
        }
        log.info("Harmonic compensation applied ({} harmonic(s)):{}", hNums.length, sb);
    }

    /**
     * Hot-swaps the intermodulation compensation on the RUNNING generator and
     * switches it to {@link GenSignalForm#DUAL_TONE_COMP} - the
     * dual-tone counterpart of {@link #applyCompensation}.  Each product is the
     * triple {@code (ampRatio, aCoef, bCoef, initial phase)} at
     * {@code a·f₁ + b·f₂}, published as one immutable {@link DualToneComp}
     * before the form flips so the audio thread never sees a partial set.
     * Empty arrays leave an uncorrected two-tone signal.
     *
     * <p>{@code ampRatio} is a ratio to the <b>F1 tone</b> - the same
     * convention the single-tone call uses against the fundamental, and the
     * one the accumulators divide by on the way out - so it is independent of
     * the dual-tone split and of the master amplitude.
     */
    public void applyDualToneCompensation(double[] ampRatios, int[] aCoef, int[] bCoef, double[] phiInits) {
        this.dtComp = new DualToneComp(ampRatios, aCoef, bCoef, phiInits);
        this.form   = GenSignalForm.DUAL_TONE_COMP;
    }

    /** Drops any compensation and returns a compensated generator to its plain
     *  tone - {@link GenSignalForm#SINE_COMP} -> {@link GenSignalForm#SINE},
     *  {@link GenSignalForm#DUAL_TONE_COMP} -> {@link GenSignalForm#DUAL_TONE}.
     *  The start of a predistortion run, which measures the raw DAC. */
    public void clearCompensation() {
        this.comp   = null;
        this.dtComp = null;
        if (form == GenSignalForm.SINE_COMP)      this.form = GenSignalForm.SINE;
        if (form == GenSignalForm.DUAL_TONE_COMP) this.form = GenSignalForm.DUAL_TONE;
    }

    /** Live-updates the second tone's frequency for the
     *  {@link GenSignalForm#DUAL_TONE} waveform.  No-op for every other
     *  form (the second accumulator only advances when the form is
     *  DUAL_TONE).  Phase-continuous like {@link #setFrequency}. */
    public void setDualToneFrequency2(double frequencyHz) {
        this.phaseInc2 = toPhaseInc(frequencyHz);
    }

    /** The second tone's frequency as the DDS is CURRENTLY driving it - the
     *  read-back of {@link #setDualToneFrequency2}, recovered from the phase
     *  increment, so a caller sees what is being emitted rather than what it
     *  believes it asked for.  Exact to the phase increment's own granularity
     *  ({@code fs/2^64}). */
    public double getDualToneFrequency2Hz() {
        return phaseInc2 / Constants.TWO_POW_64 * sampleRate;
    }

    /**
     * Starts or re-aims the pilot lines at {@code hz1} and {@code hz2}, both at
     * the absolute level {@code levelDbv} (V RMS against each lane's own DAC
     * full scale).  A {@code hz2} that is not a positive frequency - NaN is how
     * the alignment states it - asks for the first line alone and switches the
     * second off.  Live: the next frame carries them, as long as the current
     * form is a tonal one - pilots asked for under a sweep or a noise form wait
     * in {@link #pilotVrms} / {@link #pilotVrms2} and start with the next tonal
     * form.  A re-aim writes the increments and the levels and leaves both
     * accumulators alone, exactly as {@link #setDualToneFrequency2} does, so
     * each line's phase carries across it - a restart there would look like the
     * time-base drift the pilots exist to measure.
     */
    @Override
    public void setPilotTones(double hz1, double hz2, double levelDbv) {
        double vrms = Math.pow(10.0, levelDbv / DB_PER_DECADE);
        // A line that was OFF starts phase-locked to the main tone on its first
        // sample (see nextFrame); a line that is merely re-aimed keeps its
        // accumulator, so its phase carries across.
        boolean on1 = this.pilotVrms == 0.0;
        boolean on2 = hz2 > 0.0 && this.pilotVrms2 == 0.0;
        if (on1) pilotLock1Pending = true;
        this.pilotPhaseInc = toPhaseInc(hz1);
        this.pilotVrms     = vrms;
        if (hz2 > 0.0) {
            if (on2) pilotLock2Pending = true;
            this.pilotPhaseInc2 = toPhaseInc(hz2);
            this.pilotVrms2     = vrms;
        } else {
            this.pilotVrms2 = 0.0;
        }
        recomputeLevels();
        // One line per pilot event, so a log can say whether the lines were
        // switched, re-aimed or taken down when a reader loses them.
        if (log.isInfoEnabled()) {
            log.info("Pilot tones {}: {} Hz / {} Hz at {} dBV",
                    (on1 || on2) ? "switched on" : "re-aimed",
                    String.format("%.6f", hz1), String.format("%.6f", hz2),
                    String.format("%.1f", levelDbv));
        }
    }

    /** Stops both pilots: every lane level of theirs goes to zero and the third
     *  and fourth accumulators stop advancing.  Nothing of the main waveform
     *  moves - the pilots were never part of its level or of the RMS
     *  normalisation. */
    @Override
    public void clearPilotTones() {
        boolean wereOn = this.pilotVrms != 0.0 || this.pilotVrms2 != 0.0;
        this.pilotVrms  = 0.0;
        this.pilotVrms2 = 0.0;
        recomputeLevels();
        if (wereOn && log.isInfoEnabled()) log.info("Pilot tones switched off");
    }

    /** Live-updates the dual-tone amplitude split.  {@code amp1Pct} +
     *  {@code amp2Pct} are interpreted as LINEAR amplitude percentages
     *  per tone (not power) - the per-tone DDS weight is the
     *  percentage divided by 100.  Each value is clamped to
     *  {@code [0, 100]} independently.
     *
     *  <p>After updating the weights both lanes' levels are re-normalised
     *  against the new {@code rawRms() = √((w₁² + w₂²) / 2)} so the
     *  combined signal's Vrms still matches whatever was last passed to
     *  {@link #setAmplitudesVrms}.  Without the re-normalisation a
     *  50/50 split would emit a noticeably quieter signal than a 100/0
     *  single-tone case at the same Amplitude-field setting. */
    public void setDualToneAmplitudes(double amp1Pct, double amp2Pct) {
        double a1 = Math.max(0.0, Math.min(100.0, amp1Pct)) / 100.0;
        double a2 = Math.max(0.0, Math.min(100.0, amp2Pct)) / 100.0;
        this.dualW1 = a1;
        this.dualW2 = a2;
        // Re-derive the levels from the cached Vrms so the combined RMS stays
        // equal to the Amplitude field's value regardless of how the user
        // splits the two tones.
        recomputeLevels();
    }

    /**
     * Live-updates the two lanes' output amplitudes (V RMS each).  Takes effect
     * on the next frame emitted; no audible click unless the change is large.
     */
    @Override
    public void setAmplitudesVrms(double leftVrms, double rightVrms) {
        applyLanes(leftVrms, rightVrms, dacFsVoltageAmplLeft, dacFsVoltageAmplRight);
    }

    /**
     * Pushes the two lanes' DAC full-scale voltages (the user recalibrated) and
     * recomputes each lane's level from its cached requested Vrms, so a running
     * generator tracks the new full scales immediately without a restart.  The
     * owner observes the calibration preferences and forwards the values here.
     */
    @Override
    public void setDacFsVoltageAmpls(double leftAmpl, double rightAmpl) {
        applyLanes(currentVrmsLeft, currentVrmsRight, leftAmpl, rightAmpl);
    }

    /**
     * Live-updates the rectangle waveform's duty cycle.  Clamped to
     * {@code [0.001, 0.999]} so the pulse train never collapses to a
     * constant DC level.  No-op for non-rectangle forms.
     */
    public void setRectangleDuty(double duty) {
        if (Double.isNaN(duty) || Double.isInfinite(duty)) return;
        if (duty < 0.001) duty = 0.001;
        if (duty > 0.999) duty = 0.999;
        this.rectDuty = duty;
    }

    /**
     * Live-updates the triangle waveform's duty cycle (rise-portion
     * fraction).  Clamped to {@code [0.001, 0.999]} so the rise or fall
     * segment never collapses to zero width (which would produce a step
     * discontinuity).  No-op for non-triangle forms.
     */
    public void setTriangleDuty(double duty) {
        if (Double.isNaN(duty) || Double.isInfinite(duty)) return;
        if (duty < 0.001) duty = 0.001;
        if (duty > 0.999) duty = 0.999;
        this.triDuty = duty;
    }

    /**
     * The next frame, one sample per lane in [-1.0, +1.0] of digital full scale:
     * the ONE waveform sample, scaled by each lane's own level.  Advances the
     * phase accumulator by one step.  {@code frame[0]} is the left lane,
     * {@code frame[1]} the right; no allocation - the audio hot path.
     *
     * <p>The pilot lines are added HERE and not in {@link #nextRaw()}, because
     * their level is an absolute voltage per lane: they have to stay outside
     * the per-lane amplitude scaling, outside the RMS normalisation the main
     * tone's level is derived from ({@link #rawRms}), and outside every
     * predistortion kernel, which corrects the main tone alone.  Each
     * accumulator advances whenever its line is on, so every pilot's phase is a
     * continuous function of time even across a form that does not carry it.
     */
    public void nextFrame(double[] frame) {
        double raw = nextRaw();
        frame[0] = raw * amplitudeLeft;
        frame[1] = raw * amplitudeRight;
        // A line is rendered while it is asked for AND while it is still
        // fading out after being taken off - its phase keeps advancing
        // throughout, so it stays a continuous function of time.
        boolean line1 = pilotVrms  > 0.0 || pilotCurLeft  != 0.0 || pilotCurRight  != 0.0;
        boolean line2 = pilotVrms2 > 0.0 || pilotCurLeft2 != 0.0 || pilotCurRight2 != 0.0;
        if (line1 || line2) {
            boolean tonal = carriesPilot();   // one form read for both lines
            double  coef  = pilotFadeCoef;
            // The main tone's phase on THIS sample: nextRaw read it and then
            // advanced the accumulator, so it stands one increment back.
            long mainNow = phaseAcc - phaseInc;
            if (line1) {
                if (tonal) {
                    // The phase lock is taken from silence only - a line still
                    // audible would jump - so a line switched on while it
                    // fades out finishes the fade-out first, then locks and
                    // fades in.  Silence is read BEFORE this sample's step.
                    if (pilotLock1Pending && pilotCurLeft == 0.0 && pilotCurRight == 0.0) {
                        pilotPhaseAcc     = lockedToMain(mainNow, pilotPhaseInc);
                        pilotLock1Pending = false;
                        if (log.isInfoEnabled()) log.info("Pilot line 1 locked to the main tone");
                    }
                    boolean hold1 = pilotLock1Pending;
                    pilotCurLeft  = fadeToward(pilotCurLeft,  hold1 ? 0.0 : pilotAmplLeft,  coef);
                    pilotCurRight = fadeToward(pilotCurRight, hold1 ? 0.0 : pilotAmplRight, coef);
                    double pilot = SineKernel.sinAtPhaseAcc(pilotPhaseAcc);
                    frame[0] += pilot * pilotCurLeft;
                    frame[1] += pilot * pilotCurRight;
                } else {
                    // A form that carries no pilot renders it at zero, so the
                    // line fades in - and takes a pending lock - from silence
                    // when a tonal form returns.
                    pilotCurLeft  = 0.0;
                    pilotCurRight = 0.0;
                }
                pilotPhaseAcc += pilotPhaseInc;   // long overflow IS the 2^64 wrap
            }
            if (line2) {
                if (tonal) {
                    if (pilotLock2Pending && pilotCurLeft2 == 0.0 && pilotCurRight2 == 0.0) {
                        pilotPhaseAcc2    = lockedToMain(mainNow, pilotPhaseInc2);
                        pilotLock2Pending = false;
                        if (log.isInfoEnabled()) log.info("Pilot line 2 locked to the main tone");
                    }
                    boolean hold2 = pilotLock2Pending;
                    pilotCurLeft2  = fadeToward(pilotCurLeft2,  hold2 ? 0.0 : pilotAmplLeft2,  coef);
                    pilotCurRight2 = fadeToward(pilotCurRight2, hold2 ? 0.0 : pilotAmplRight2, coef);
                    double pilot = SineKernel.sinAtPhaseAcc(pilotPhaseAcc2);
                    frame[0] += pilot * pilotCurLeft2;
                    frame[1] += pilot * pilotCurRight2;
                } else {
                    pilotCurLeft2  = 0.0;
                    pilotCurRight2 = 0.0;
                }
                pilotPhaseAcc2 += pilotPhaseInc2;
            }
        }
    }

    /** A pilot accumulator phase-locked to the main tone: the main tone's
     *  phase, as a fraction of a turn, times the ratio of the two increments -
     *  which is the ratio of the two frequencies - wrapped to a turn.  Read
     *  through 53 bits of the accumulator, so the lock is exact to 2^-53 of a
     *  turn before the ratio scales it; the lowest bit of the result is not
     *  kept, which is 2^-63 of a turn.  Zero where the main tone has no
     *  increment to scale by. */
    private long lockedToMain(long mainAcc, long pilotInc) {
        long inc = phaseInc;
        if (inc == 0L) return 0L;
        double turns = (mainAcc >>> 11) / 0x1p53;
        double frac  = turns * ((double) pilotInc / (double) inc);
        frac -= Math.floor(frac);
        return ((long) (frac * 0x1p63)) << 1;
    }

    /** Whether a pilot line may ride on the frames this source renders: the
     *  tonal DDS forms carry one, the sweeps and the noise forms do not (their
     *  spectrum is the measurement), and a source whose samples are not a DDS
     *  waveform at all carries none. */
    protected boolean carriesPilot() {
        GenSignalForm f = form;               // single volatile read
        return f == GenSignalForm.SINE      || f == GenSignalForm.SINE_COMP
            || f == GenSignalForm.DUAL_TONE || f == GenSignalForm.DUAL_TONE_COMP;
    }

    /** The next sample of the waveform itself, at unit level, advancing the
     *  phase accumulator by one step - what every lane is scaled from.  A
     *  source that is not a waveform (a file) overrides this alone. */
    protected double nextRaw() {
        double raw = switch (form) {
            case SINE              -> ddsSine();
            case TRIANGLE          -> ddsTriangle();
            case RECTANGLE         -> ddsRectangle();
            case WHITE_NOISE       -> rng.nextGaussian();
            case PINK_NOISE        -> pinkNoise(false);
            case PINK_NOISE_LINEAR -> pinkNoise(true);
            case SINE_COMP  -> ddsSineCompensated();
            case LINEAR_SWEEP      -> linearSweepNext();
            case LOG_SWEEP         -> logSweepNext();
            case DUAL_TONE         -> ddsSine() * dualW1 + ddsSine2() * dualW2;
            case DUAL_TONE_COMP -> ddsDualToneCompensated();
        };
        phaseAcc  += phaseInc;    // long overflow IS the 2^64 phase wrap
        // The second accumulator only advances for the two-tone forms.
        // Cheap branch - the audio loop already executed the per-form
        // switch and form is volatile-cached locally by the JIT.
        if (form == GenSignalForm.DUAL_TONE || form == GenSignalForm.DUAL_TONE_COMP) {
            phaseAcc2 += phaseInc2;
        }
        return raw;
    }

    /**
     * Linear-sweep kernel: phase-continuous chirp whose instantaneous frequency
     * advances linearly from {@code sweepFreqStart} to {@code sweepFreqEnd}
     * across {@code sweepPeriodSamples} samples.  Loops back to the start when
     * {@link #sweepLoop} is true (phase-continuous restart so the DAC sees no
     * clicks); otherwise goes silent after one cycle.  Hann fade in/out
     * smooths the cycle edges if configured.
     */
    private double linearSweepNext() {
        if (sweepIdx >= sweepPeriodSamples) {
            if (!sweepLoop) return 0.0;
            sweepIdx   = 0;
            sweepPhase = 0.0;
        }
        double frac  = sweepIdx / (double) sweepPeriodSamples;
        double instF = sweepFreqStart + (sweepFreqEnd - sweepFreqStart) * frac;
        double s     = Math.sin(sweepPhase);
        sweepPhase  += 2.0 * Math.PI * instF / sweepSampleRate;
        // Wrap to keep phase magnitude bounded for double precision.
        if (sweepPhase >= 2.0 * Math.PI) {
            sweepPhase -= 2.0 * Math.PI * Math.floor(sweepPhase / (2.0 * Math.PI));
        }
        double env = sweepEnvelope(sweepIdx, sweepPeriodSamples);
        sweepIdx++;
        return s * env;
    }

    /**
     * Log-sweep kernel: emits {@code logSweepLeadIn} zeros, then replays the
     * pre-rendered {@code logSweepBuffer} sample-by-sample.  When
     * {@link #sweepLoop} is true the buffer is replayed back-to-back (without
     * re-emitting the lead-in silence); otherwise the output stays at zero
     * after the first cycle.  Hann fade in/out is applied per cycle.
     */
    private double logSweepNext() {
        // Snapshot the buffer reference: the UI thread swaps in a new array
        // on live parameter changes, and indexing the field directly after
        // validating against an earlier read can index past a shorter
        // replacement (AIOOBE on the audio thread).
        double[] buf = logSweepBuffer;
        if (logSweepRestart.get() && logSweepRestart.getAndSet(false)) {
            logSweepIdx = logSweepLeadIn;
        }
        long idx = logSweepIdx++;
        if (idx < logSweepLeadIn) return 0.0;
        long sIdx = idx - logSweepLeadIn;
        int bufLen = buf.length;
        if (sIdx >= bufLen) {
            if (!sweepLoop) return 0.0;
            // Wrap back to the start of the buffer (skip lead-in on
            // subsequent cycles).  logSweepIdx is at the next sample
            // after the just-emitted one - set it so the next call lands
            // at bufIdx = 0.
            long completed = (sIdx - 1) / bufLen + 1;
            logSweepIdx = logSweepLeadIn + (sIdx - completed * bufLen) + 1;
            sIdx = sIdx % bufLen;
        }
        int bufIdx = (int) sIdx;
        double env = sweepEnvelope(bufIdx, bufLen);
        return buf[bufIdx] * env;
    }

    /** Returns the Hann fade envelope value for sample {@code idx} within a
     *  cycle of length {@code cycleLength}.  Fade in covers the first
     *  {@link #fadeInSamples}; fade out covers the last {@link #fadeOutSamples}.
     *  Returns 1.0 in the steady-state middle of the cycle, or when the
     *  fade lengths are 0. */
    private double sweepEnvelope(int idx, int cycleLength) {
        int fIn = fadeInSamples;
        int fOut = fadeOutSamples;
        if (fIn > 0 && idx < fIn) {
            return 0.5 * (1.0 - Math.cos(Math.PI * idx / fIn));
        }
        if (fOut > 0 && idx >= cycleLength - fOut) {
            int back = cycleLength - 1 - idx;
            if (back < 0) back = 0;
            return 0.5 * (1.0 - Math.cos(Math.PI * back / fOut));
        }
        return 1.0;
    }

    /** Live-applies sweep loop and fade parameters; safe to call after
     *  construction.  Fade lengths are clamped to half the sweep cycle
     *  so the in-fade and out-fade can never overlap. */
    public void setSweepParams(boolean loop, int fadeInSamples, int fadeOutSamples) {
        this.sweepLoop = loop;
        int cycle = sweepCycleLength();
        int half = Math.max(0, cycle / 2);
        this.fadeInSamples  = Math.max(0, Math.min(fadeInSamples,  half));
        this.fadeOutSamples = Math.max(0, Math.min(fadeOutSamples, half));
    }

    /** Live-applies sweep start frequency (Hz).  Triggers LOG_SWEEP buffer
     *  regeneration since the pre-rendered buffer depends on it. */
    public void setSweepFreqStart(double hz) {
        if (!Double.isFinite(hz) || hz < 0) return;
        if (form == GenSignalForm.LINEAR_SWEEP) {
            sweepFreqStart = hz;
        } else if (form == GenSignalForm.LOG_SWEEP) {
            sweepFreqStart = hz;
            rebuildLogSweepBuffer();
        }
    }

    /** Live-applies sweep stop frequency (Hz). */
    public void setSweepFreqEnd(double hz) {
        if (!Double.isFinite(hz) || hz < 0) return;
        if (form == GenSignalForm.LINEAR_SWEEP) {
            sweepFreqEnd = hz;
        } else if (form == GenSignalForm.LOG_SWEEP) {
            sweepFreqEnd = hz;
            rebuildLogSweepBuffer();
        }
    }

    /** Live-applies sweep duration in samples.  For LINEAR_SWEEP just
     *  updates the period counter; for LOG_SWEEP rebuilds the pre-rendered
     *  buffer. */
    public void setSweepDurationSamples(int samples) {
        if (samples < 2) samples = 2;
        if (form == GenSignalForm.LINEAR_SWEEP) {
            // No sweepIdx reset here: linearSweepNext() wraps an
            // out-of-range index itself, and position state is
            // audio-thread-owned.
            sweepPeriodSamples = samples;
            reclampFadeToCycle();
        } else if (form == GenSignalForm.LOG_SWEEP) {
            // Allocate a new buffer at the requested length so subsequent
            // logSweepNext() reads see the new size.  The restart request
            // makes the audio thread rewind to the start of the buffer
            // (skip lead-in) so the user doesn't get stuck halfway through
            // an outdated cycle.
            double[] fresh = renderLogSweep(sweepFreqStart, sweepFreqEnd, samples, sampleRate);
            this.logSweepBuffer = fresh;
            logSweepRestart.set(true);
            reclampFadeToCycle();
        }
    }

    /** Re-renders the LOG_SWEEP buffer for the current start/stop/duration
     *  values.  Called after any of those change so the playback sample
     *  source actually reflects the new parameters. */
    private void rebuildLogSweepBuffer() {
        if (form != GenSignalForm.LOG_SWEEP) return;
        int len = (logSweepBuffer != null) ? logSweepBuffer.length : 0;
        if (len < 2) return;
        this.logSweepBuffer = renderLogSweep(sweepFreqStart, sweepFreqEnd, len, sampleRate);
        // Rewind playback to the start of the new buffer so the user hears
        // the new sweep from the beginning instead of a discontinuity -
        // via the restart request so only the audio thread writes position.
        logSweepRestart.set(true);
    }

    /** Returns the current sweep-cycle length in samples (period for
     *  LINEAR_SWEEP, buffer length for LOG_SWEEP, 0 for non-sweep forms). */
    private int sweepCycleLength() {
        if (form == GenSignalForm.LINEAR_SWEEP) return sweepPeriodSamples;
        if (form == GenSignalForm.LOG_SWEEP   ) return (logSweepBuffer != null) ? logSweepBuffer.length : 0;
        return 0;
    }

    /** Re-clamps the fade lengths to the new cycle length after a
     *  duration change.  Keeps the in-fade + out-fade from overlapping. */
    private void reclampFadeToCycle() {
        int cycle = sweepCycleLength();
        int half = Math.max(0, cycle / 2);
        if (fadeInSamples  > half) fadeInSamples  = half;
        if (fadeOutSamples > half) fadeOutSamples = half;
    }

    /** Live-applies sweep fade-in length (samples). */
    public void setSweepFadeInSamples(int samples) {
        int half = Math.max(0, sweepCycleLength() / 2);
        this.fadeInSamples = Math.max(0, Math.min(samples, half));
    }

    /** Live-applies sweep fade-out length (samples). */
    public void setSweepFadeOutSamples(int samples) {
        int half = Math.max(0, sweepCycleLength() / 2);
        this.fadeOutSamples = Math.max(0, Math.min(samples, half));
    }

    /** Live-applies the sweep loop flag. */
    public void setSweepLoop(boolean loop) {
        this.sweepLoop = loop;
    }

    // -------------------------------------------------------------------------
    // DDS waveform kernels
    // -------------------------------------------------------------------------

    /**
     * DDS sine - the shared table-plus-Taylor kernel evaluated on this
     * oscillator's 64-bit phase accumulator (see {@link SineKernel} for the
     * table split and the switchable 5th/7th/9th-order correction).
     */
    private double ddsSine() {
        return SineKernel.sinAtPhaseAcc(phaseAcc);
    }

    /** Second DDS sine reader - identical math to {@link #ddsSine}, but
     *  reads {@link #phaseAcc2} instead of {@link #phaseAcc} so the
     *  dual-tone waveform can run two independent oscillators in lock-
     *  step with a single sample tick. */
    private double ddsSine2() {
        return SineKernel.sinAtPhaseAcc(phaseAcc2);
    }

    /**
     * DDS rectangle / pulse train.  Output is {@code +1} for the first
     * {@link #dutySamples} samples of the period, {@code −1} for the rest.
     * A 50 % duty cycle produces a symmetric square wave; other duty values
     * have a non-zero DC component which is the user's intent for pulse-
     * style test signals.
     *
     * <p>Whole samples, not the phase fraction: the rectangle runs at a
     * period-aligned frequency (a whole number {@code n} of samples per
     * period), so the duty the operator sees is {@code k/n} - the count the
     * duty bracket shows.  Comparing the phase fraction with the duty instead
     * left a duty below one sample to the accumulator's rounding: whether the
     * one sample of the period fell inside the fraction depended on which side
     * of the full turn the residual landed, and the pulse vanished entirely.
     */
    private double ddsRectangle() {
        double frac = (phaseAcc >>> 11) * Constants.ONE_OVER_2_53;   // [0, 1) - top 53 bits (all a double holds)
        int n = periodSamples();
        return sampleOfPeriod(frac, n) < dutySamples(rectDuty, n) ? +1.0 : -1.0;
    }

    /**
     * DDS triangle with adjustable duty cycle.  The rising portion takes
     * {@link #dutySamples} samples of the period (−1 -> +1), the falling
     * portion takes the remainder (+1 -> −1).  At {@code triDuty = 0.5} the
     * waveform is a symmetric triangle; near {@code 1.0} it approaches a
     * sawtooth; near {@code 0.0} it approaches an inverted sawtooth.
     * Piecewise-linear in the phase domain - exact by construction, and the
     * corner lands ON a sample of the period-aligned grid, as the duty
     * bracket shows.
     */
    private double ddsTriangle() {
        double frac = (phaseAcc >>> 11) * Constants.ONE_OVER_2_53;   // [0, 1) - top 53 bits (all a double holds)
        int n = periodSamples();
        double d = (double) dutySamples(triDuty, n) / n;
        if (frac < d) {
            return frac / d * 2.0 - 1.0;
        } else {
            return 1.0 - (frac - d) / (1.0 - d) * 2.0;
        }
    }

    /** Samples per period on the period-aligned grid the rectangle and
     *  triangle edges live on - {@code max(2, round(fs / f))}, the same count
     *  the generator pane's duty bracket divides by. */
    private int periodSamples() {
        double f = frequencyHz;
        if (f <= 0.0) return 2;
        return Math.max(2, (int) Math.round(sampleRate / f));
    }

    /** The whole samples a duty spans in a period of {@code n}: rounded, and
     *  never the whole period or none of it - at least one sample high and one
     *  low, the clamp the duty bracket applies, so the pulse emitted is the
     *  pulse the bracket shows. */
    private int dutySamples(double duty, int n) {
        int k = (int) Math.round(duty * n);
        return Math.max(1, Math.min(n - 1, k));
    }

    /** The sample of the period a phase falls on.  On the aligned grid every
     *  phase is a multiple of {@code 1/n} up to the accumulator's rounding, so
     *  the NEAREST multiple is the sample; a phase a hair below the full turn is
     *  sample 0 of the next period. */
    private int sampleOfPeriod(double frac, int n) {
        int i = (int) Math.round(frac * n);
        return i >= n ? i - n : i;
    }

