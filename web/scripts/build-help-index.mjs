/*
 * Phonalyser web — build-time help search index generator.
 *
 * Walks web/help/<lang>/**.html and (re)writes web/help/<lang>/search-index.js defining
 *   window.HELP_DOCS = [{id, u, a, t, h, x}]
 * — one doc per page intro (a="") plus one per anchored (id-bearing) h2/h3 section.
 * help-index.html loads lunr + this file and builds the lunr index IN-BROWSER from
 * HELP_DOCS, so regenerating it here every build keeps search in sync with edited help.
 *
 * Dep-free: a small tag-stripping + entity-decoding text extractor (the help HTML is our
 * own static markup, not arbitrary input). Run standalone (node scripts/build-help-index.mjs)
 * or via build.mjs (imports buildHelpIndex()).
 * GNU AGPL v3 or later.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const HELP_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../help');

// Named entities that appear in the help prose; numeric (&#…;) handled generically.
const NAMED = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', mdash: '—',
  ndash: '–', hellip: '…', times: '×', divide: '÷', deg: '°', micro: 'µ', radic: '√',
  infin: '∞', sup2: '²', sup3: '³', frac12: '½', le: '≤', ge: '≥', ne: '≠', approx: '≈',
  plusmn: '±', minus: '−', rarr: '→', larr: '←', sigma: 'σ', Sigma: 'Σ', Delta: 'Δ',
  phi: 'φ', theta: 'θ', omega: 'ω', pi: 'π', alpha: 'α', beta: 'β' };

function decode(s) {
  return s.replace(/&(#x?[0-9a-f]+|[a-z0-9]+);/gi, (m, e) => {
    if (e[0] === '#') {
      const code = (e[1] === 'x' || e[1] === 'X') ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      return Number.isFinite(code) ? String.fromCodePoint(code) : m;
    }
    return e in NAMED ? NAMED[e] : (e.toLowerCase() in NAMED ? NAMED[e.toLowerCase()] : m);
  });
}

/** HTML fragment → clean searchable text: drop script/style/svg, strip tags, decode, collapse. */
function toText(html) {
  return decode(html
    .replace(/<(script|style|svg)\b[\s\S]*?<\/\1>/gi, ' ')
    .replace(/<[^>]+>/g, ' '))
    .replace(/\s+/g, ' ')
    .trim();
}

function pageTitle(html) {
  const m = /<h1\b[^>]*>([\s\S]*?)<\/h1>/i.exec(html);
  return m ? toText(m[1]) : '';
}

/** Recursively collect .html pages under a language dir (skip the search page itself). */
async function listPages(dir, base = dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) { out.push(...await listPages(full, base)); continue; }
    if (!e.name.endsWith('.html') || e.name === 'help-index.html') continue;
    out.push({ full, u: path.relative(base, full).replace(/\\/g, '/') });
  }
  return out;
}

/** A page → its docs: the intro (a="") + one per id-bearing h2/h3, each carrying the text
 *  from that heading up to the next anchored heading. */
function docsForPage(html, u, title, startId) {
  const body = (/<body\b[^>]*>([\s\S]*)<\/body>/i.exec(html) || [, html])[1];
  const boundRe = /<(h[23])\b[^>]*\bid="([^"]+)"[^>]*>([\s\S]*?)<\/\1>/gi;
  const bounds = [];
  let m;
  while ((m = boundRe.exec(body))) bounds.push({ at: m.index, end: boundRe.lastIndex, a: m[2], h: toText(m[3]) });

  const docs = [];
  let id = startId;
  const h1 = /<h1\b[^>]*>[\s\S]*?<\/h1>/i.exec(body);
  const introStart = h1 ? h1.index + h1[0].length : 0;
  const introEnd = bounds.length ? bounds[0].at : body.length;
  docs.push({ id: id++, u, a: '', t: title, h: title, x: toText(body.slice(introStart, introEnd)) });
  for (let i = 0; i < bounds.length; i++) {
    const segEnd = (i + 1 < bounds.length) ? bounds[i + 1].at : body.length;
    docs.push({ id: id++, u, a: bounds[i].a, t: title, h: bounds[i].h, x: toText(body.slice(bounds[i].end, segEnd)) });
  }
  return docs;
}

async function buildOneLang(langDir) {
  const pages = await listPages(langDir);
  pages.sort((a, b) => a.u.localeCompare(b.u));
  const docs = [];
  for (const p of pages) {
    const html = await readFile(p.full, 'utf8');
    docs.push(...docsForPage(html, p.u, pageTitle(html), docs.length));
  }
  const out = '/* GENERATED by scripts/build-help-index.mjs — do not edit. */\n'
    + 'window.HELP_DOCS = ' + JSON.stringify(docs) + ';\n';
  await writeFile(path.join(langDir, 'search-index.js'), out);
  return docs.length;
}

/** Regenerate search-index.js for every language under web/help/. Returns a per-lang count. */
export async function buildHelpIndex() {
  const langs = (await readdir(HELP_DIR, { withFileTypes: true })).filter((d) => d.isDirectory());
  const counts = {};
  for (const l of langs) counts[l.name] = await buildOneLang(path.join(HELP_DIR, l.name));
  return counts;
}

// Standalone invocation.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const counts = await buildHelpIndex();
  for (const [lang, n] of Object.entries(counts)) console.log(`help index: ${lang} -> ${n} docs`);
}
