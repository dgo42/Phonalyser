/*
 * Stream test for the scope MEASUREMENT compute engine (osc-meas-compute.js).
 *
 * Drives the REAL streaming engine the way the client does - contiguous 100 ms
 * batches fed gaplessly, the rolling collection window, a fixed ~100 ms publish
 * cadence - and asserts the published measurements per the measurement-worker spec:
 *
 *   DUAL  9999.023 / 11000.977 Hz @ 192 k, +3 µV DC, 6 s run, 5 s window:
 *     - published Vmean settles < 1 µV error
 *     - refined dualF1 / dualF2 within 1e-4 Hz
 *     - Vmean stays whole-beat-aligned as the window slides (spread across the last
 *       second of publishes < 1 µV)
 *
 *   SINGLE 999.02 Hz @ 192 k, +3 µV DC, 6 s run, 5 s window:
 *     - whole-carrier alignment: published Vmean settles < 1 µV error
 *
 * Run:  node test/osc-meas-stream.test.mjs
 */
globalThis.performance = globalThis.performance || { now: () => Date.now() };

import { OscMeasCompute } from '../js/scope/osc-meas-compute.js';

let passed = 0, failed = 0;
function ok(cond, msg) { if (cond) passed++; else { failed++; console.error('FAIL:', msg); } }

const SR = 192000;
const PEAK = 1.0;           // normalized -> volts 1:1
const DC = 3e-6;            // +3 µV DC pedestal
const AVG_SEC = 5.0;        // collection window
const RUN_SEC = 6.0;
const BATCH_SEC = 0.1;      // 100 ms contiguous batches
const BATCH_N = Math.round(BATCH_SEC * SR);
const PUBLISH_MS = 100;     // fixed cadence

// Streams `totalSec` of a signal generated by `sample(absK)` through the engine in
// contiguous BATCH_N batches, publishing every ~PUBLISH_MS. Returns the array of
// published Vmean values (channel L) and the last full measurement.
function runStream(sample, opts) {
  const eng = new OscMeasCompute();
  const total = Math.round(opts.totalSec * SR);
  const batch = new Float32Array(BATCH_N);
  const feedOpts = { mainsMode: 'NONE', avgSeconds: AVG_SEC };
  const pubOpts = { mainsMode: 'NONE', dual: opts.dual, f1Hz: opts.f1Hz, f2Hz: opts.f2Hz };
  const vmeans = [];
  let last = null;
  let absK = 0;
  let sincePublishMs = 0;
  const perBatchMs = BATCH_SEC * 1000;
  while (absK < total) {
    const n = Math.min(BATCH_N, total - absK);
    for (let i = 0; i < n; i++) batch[i] = sample(absK + i);
    eng.feed('L', batch, n, SR, feedOpts);
    absK += n;
    sincePublishMs += perBatchMs;
    while (sincePublishMs >= PUBLISH_MS) {
      sincePublishMs -= PUBLISH_MS;
      const m = eng.publish('L', SR, PEAK, pubOpts);
      if (m) { vmeans.push(m.vmean); last = m; }
    }
  }
  return { vmeans, last };
}

// ===== DUAL: 9999.023 / 11000.977 Hz, +3 µV DC =====
{
  const f1 = 9999.023, f2 = 11000.977, amp = 0.4, ph1 = 0.37, ph2 = 1.13;
  const { vmeans, last } = runStream(
    (k) => DC + amp * Math.sin(2 * Math.PI * f1 * k / SR + ph1)
              + amp * Math.sin(2 * Math.PI * f2 * k / SR + ph2),
    { totalSec: RUN_SEC, dual: true, f1Hz: f1, f2Hz: f2 });

  ok(vmeans.length > 0, 'DUAL: published at least once');
  const vm = last.vmean;
  console.log(`[DUAL] final Vmean=${vm.toExponential(4)} (want ${DC.toExponential(4)})  dualF1=${last.dualF1 && last.dualF1.toFixed(5)} dualF2=${last.dualF2 && last.dualF2.toFixed(5)}`);
  ok(Math.abs(vm - DC) < 1e-6, `DUAL: Vmean settles < 1 µV err (|${vm.toExponential(3)} − ${DC.toExponential(3)}| = ${Math.abs(vm - DC).toExponential(3)})`);
  ok(Number.isFinite(last.dualF1) && Math.abs(last.dualF1 - f1) < 1e-4,
     `DUAL: dualF1 within 1e-4 Hz (${last.dualF1 && last.dualF1.toFixed(6)} vs ${f1})`);
  ok(Number.isFinite(last.dualF2) && Math.abs(last.dualF2 - f2) < 1e-4,
     `DUAL: dualF2 within 1e-4 Hz (${last.dualF2 && last.dualF2.toFixed(6)} vs ${f2})`);

  // Whole-beat alignment while the window slides: over the last second of publishes the
  // Vmean must not swing (fractional-beat residual would jitter it). Spread < 1 µV.
  const tail = vmeans.slice(-10);   // last ~1 s at 100 ms cadence
  let mn = tail[0], mx = tail[0];
  for (const v of tail) { if (v < mn) mn = v; if (v > mx) mx = v; }
  console.log(`[DUAL] tail Vmean spread=${(mx - mn).toExponential(3)} over ${tail.length} publishes`);
  ok((mx - mn) < 1e-6, `DUAL: Vmean whole-beat-aligned as window slides (spread ${(mx - mn).toExponential(3)} < 1 µV)`);
}

// ===== SINGLE: 999.02 Hz, +3 µV DC =====
{
  const f = 999.02, amp = 0.4, ph = 0.5;
  const { vmeans, last } = runStream(
    (k) => DC + amp * Math.sin(2 * Math.PI * f * k / SR + ph),
    { totalSec: RUN_SEC, dual: false, f1Hz: f, f2Hz: 0 });

  ok(vmeans.length > 0, 'SINGLE: published at least once');
  const vm = last.vmean;
  console.log(`[SINGLE] final Vmean=${vm.toExponential(4)} (want ${DC.toExponential(4)})  f=${last.frequency && last.frequency.toFixed(4)}`);
  ok(Math.abs(vm - DC) < 1e-6, `SINGLE: whole-carrier Vmean settles < 1 µV err (|${vm.toExponential(3)} − ${DC.toExponential(3)}| = ${Math.abs(vm - DC).toExponential(3)})`);

  const tail = vmeans.slice(-10);
  let mn = tail[0], mx = tail[0];
  for (const v of tail) { if (v < mn) mn = v; if (v > mx) mx = v; }
  console.log(`[SINGLE] tail Vmean spread=${(mx - mn).toExponential(3)}`);
  ok((mx - mn) < 1e-6, `SINGLE: Vmean whole-carrier-aligned as window slides (spread ${(mx - mn).toExponential(3)} < 1 µV)`);
}

// ===== per-channel peak scaling =====
// The worker now threads each channel's OWN ADC full-scale (peakVoltsL / peakVoltsR from
// getAdcPeakVolts(L)/(R)) into publish(); this asserts the publish contract that makes that
// per-channel - the SAME collection window published at 2× the peak yields exactly 2×
// Vpp / Vrms / Vmean, so a differently-calibrated R channel scales independently of L.
{
  const f = 999.02, amp = 0.4, ph = 0.5;
  const eng = new OscMeasCompute();
  const total = Math.round(2.0 * SR);
  const batch = new Float32Array(BATCH_N);
  const feedOpts = { mainsMode: 'NONE', avgSeconds: AVG_SEC };
  const pubOpts = { mainsMode: 'NONE', dual: false, f1Hz: f, f2Hz: 0 };
  let absK = 0;
  while (absK < total) {
    const n = Math.min(BATCH_N, total - absK);
    for (let i = 0; i < n; i++) batch[i] = DC + amp * Math.sin(2 * Math.PI * f * (absK + i) / SR + ph);
    eng.feed('L', batch, n, SR, feedOpts);
    absK += n;
  }
  const m1 = eng.publish('L', SR, 1.0, pubOpts);
  const m2 = eng.publish('L', SR, 2.0, pubOpts);
  ok(m1 && m2, 'PEAK-SCALE: both publishes returned a measurement');
  ok(Math.abs(m2.vpp - 2 * m1.vpp) < 1e-9, `PEAK-SCALE: Vpp scales with peakVolts (${m2.vpp} vs 2×${m1.vpp})`);
  ok(Math.abs(m2.vrms - 2 * m1.vrms) < 1e-9, `PEAK-SCALE: Vrms scales with peakVolts (${m2.vrms} vs 2×${m1.vrms})`);
  ok(Math.abs(m2.vmean - 2 * m1.vmean) < 1e-12, `PEAK-SCALE: Vmean scales with peakVolts (${m2.vmean} vs 2×${m1.vmean})`);
}

console.log(`\nosc-meas-stream: ${passed} passed, ${failed} failed`);
process.exit(failed ? 1 : 0);
